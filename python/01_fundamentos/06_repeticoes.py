# AULA 6 - Repeticoes (for e while)

# for repete um numero conhecido de vezes. range(1, 6) vai de 1 ate 5.
for i in range(1, 6):
    print("Contagem:", i)

# while repete enquanto a condicao for verdadeira.
n = 3
while n > 0:
    print("Faltam", n)
    n -= 1
print("Fim!")

